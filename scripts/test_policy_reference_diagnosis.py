#!/usr/bin/env python3
"""Actual frontend boundary tests and false-acceptance controls; no quality gold."""
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('diagnosis_check', ROOT / 'scripts/check-policy-reference-diagnosis.py')
guard = importlib.util.module_from_spec(spec)
spec.loader.exec_module(guard)

class FrontendTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory(prefix='ks-policy-probe-tests-', dir='/private/tmp')
        cls.addClassCleanup(cls.tmp.cleanup)
        cls.folder = Path(cls.tmp.name)
        module = cls.folder / 'module'
        module.mkdir()
        archive = subprocess.check_output(['git', 'archive', '179d1c8d', '--', 'go.mod', 'go.sum',
            'internal/graph/parse', 'pkg/graph/policy', 'pkg/graph/types'], cwd=ROOT)
        subprocess.run(['tar', '-x', '-C', str(module)], input=archive, check=True)
        command = module / 'cmd/policy-reference-probe'
        command.mkdir(parents=True)
        (command / 'main.go').write_bytes((ROOT / 'scripts/policy_reference_probe.go.txt').read_bytes())
        cls.binary = cls.folder / 'probe'
        env = dict(os.environ, GOTOOLCHAIN='go1.26.9', GOCACHE='/private/tmp/ks-corpus-go-cache', GOPROXY='off')
        subprocess.run(['go', 'build', '-o', str(cls.binary), './cmd/policy-reference-probe'], cwd=module,
                       env=env, check=True, capture_output=True, timeout=180)

    def run_probe(self, files, before, after=None, check=True):
        old = self.folder / 'original.yaml'
        new = self.folder / 'proposed.yaml'
        def policy(target):
            return 'policies:\n  - id: probe\n    name: Probe\n    governs:\n      - ' + target + '\n'
        old.write_text(policy(before))
        new.write_text(policy(before if after is None else after))
        result = subprocess.run([str(self.binary)], input=json.dumps({'Files': files,
            'OriginalPolicy': str(old), 'ProposedPolicy': str(new)}).encode(), capture_output=True, timeout=30)
        if check:
            result.check_returncode()
            return json.loads(result.stdout)
        return result

    def test_package_declaration_and_receiver_determine_qname(self):
        result = self.run_probe([{'Path': 'compiler/compiler.go', 'Source':
            'package compile\ntype compiledTy int\nfunc (c *compiledTy) ExportContractCode() {}\n'}],
            'compiler.compiledTy.ExportContractCode', 'compile.compiledTy.ExportContractCode')
        self.assertEqual(len(result['original']['result']['Warnings']), 1)
        match = result['proposed']['references'][0]['matches'][0]
        self.assertEqual((match['type'], match['path']), ('Method', 'compiler/compiler.go'))

    def test_silent_unique_wrong_package_match_has_no_warning(self):
        result = self.run_probe([
            {'Path': 'assembler/compiler.go', 'Source': 'package compiler\nfunc Compile() {}\n'},
            {'Path': 'contracts/compiler.go', 'Source': 'package compile\nfunc Compile() {}\n'}],
            'compiler.Compile', 'compile.Compile')
        self.assertFalse(result['original']['result']['Warnings'])
        self.assertEqual(result['original']['references'][0]['matches'][0]['path'], 'assembler/compiler.go')
        self.assertEqual(result['proposed']['references'][0]['matches'][0]['path'], 'contracts/compiler.go')

    def test_missing_receiver_is_not_short_name_resolved(self):
        result = self.run_probe([{'Path': 'pool.go', 'Source':
            'package pool\ntype Pool int\nfunc (p *Pool) queue() {}\n'}], 'pool.queue', 'pool.Pool.queue')
        self.assertFalse(result['original']['result']['Edges'])
        self.assertEqual(len(result['proposed']['result']['Edges']), 1)

    def test_duplicate_qname_is_reported_even_when_resolver_chooses_last(self):
        result = self.run_probe([
            {'Path': 'a/x.go', 'Source': 'package same\nfunc Target() {}\n'},
            {'Path': 'b/x.go', 'Source': '// different offset\npackage same\nfunc Target() {}\n'}], 'same.Target')
        matches = result['original']['references'][0]['matches']
        self.assertEqual(len(matches), 2)
        self.assertEqual(result['original']['result']['Edges'][0]['src'], matches[-1]['id'])
        self.assertFalse(result['type_aware'])

    def test_generated_file_exclusion_is_explicit(self):
        result = self.run_probe([{'Path': 'generated.go', 'Source':
            '// Code generated by fixture. DO NOT EDIT.\npackage sample\nfunc Target() {}\n'}], 'sample.Target')
        self.assertEqual(result['generated_skipped'], ['generated.go'])
        self.assertFalse(result['original']['result']['Edges'])

    def test_invalid_source_is_failure_not_zero_warning_success(self):
        result = self.run_probe([{'Path': 'bad.go', 'Source': 'package !'}], 'bad.Target', check=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertFalse(result.stdout)

class PacketTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix='ks-policy-diagnosis-packet-', dir='/private/tmp')
        self.addCleanup(self.tmp.cleanup)
        self.folder = Path(self.tmp.name) / 'packet'
        shutil.copytree(guard.PACKET, self.folder)

    def mutate(self, name, action):
        path = self.folder / name
        data = json.loads(path.read_text())
        action(data)
        path.write_text(json.dumps(data))
        if name != 'manifest.json':
            manifest = json.loads((self.folder / 'manifest.json').read_text())
            for row in manifest['artifacts']:
                if row['path'] == name:
                    row.update(sha256=hashlib.sha256(path.read_bytes()).hexdigest(), bytes=path.stat().st_size)
            (self.folder / 'manifest.json').write_text(json.dumps(manifest))

    def test_current_packet_is_preparation_only(self):
        self.assertEqual(guard.check(self.folder), [])

    def test_rehashed_adoption_or_acceptance_is_rejected(self):
        self.mutate('manifest.json', lambda d: d.update(proposed_overlay_applied=True, approved_corrections=7))
        self.assertTrue(guard.check(self.folder))

    def test_rehashed_graph_success_cannot_claim_quality(self):
        self.mutate('probe.stdout.json', lambda d: d.update(approved=True, independent_acceptance='accepted'))
        self.assertTrue(guard.check(self.folder))

    def test_rehashed_wrong_source_match_is_rejected(self):
        self.mutate('probe.stdout.json', lambda d: d['proposed']['references'][0]['matches'].clear())
        self.assertTrue(guard.check(self.folder))

    def test_rehashed_correction_approval_is_rejected(self):
        self.mutate('correction-proposals.json', lambda d: d['changes'][0].update(approved=True))
        self.assertTrue(guard.check(self.folder))

    def test_artifact_escape_is_rejected(self):
        self.mutate('manifest.json', lambda d: d['artifacts'][0].update(path='../outside'))
        self.assertTrue(guard.check(self.folder))

    def test_tampered_raw_bytes_are_rejected(self):
        (self.folder / 'probe.stdout.json').write_text('{}')
        self.assertTrue(guard.check(self.folder))

if __name__ == '__main__':
    unittest.main()
