#!/usr/bin/env python3
"""Inventory is source syntax, never detector truth or independent gold."""
import importlib.util
import json
from pathlib import Path
import subprocess
import tempfile
import unittest

ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('prepare',ROOT/'scripts/prepare-policy-security-inputs.py')
prepare=importlib.util.module_from_spec(spec);spec.loader.exec_module(prepare)

class InventoryTests(unittest.TestCase):
 @classmethod
 def setUpClass(cls):
  cls.temp=tempfile.TemporaryDirectory(prefix='ks-source-inventory-test-',dir='/private/tmp')
  root=Path(cls.temp.name);source=root/'main.go';source.write_bytes((ROOT/'scripts/acceptance_source_inventory.go.txt').read_bytes())
  cls.binary=root/'inventory'
  subprocess.run(['go','build','-o',str(cls.binary),str(source)],capture_output=True,check=True,timeout=120)
 @classmethod
 def tearDownClass(cls):cls.temp.cleanup()
 def extract(self,source,other=None):
  rows=[{'Path':'logic.go','Source':source,'Blob':'unit-test-source'}]
  if other:rows.append({'Path':'other.go','Source':other,'Blob':'other-unit-source'})
  p=subprocess.run([str(self.binary)],input=json.dumps(rows),capture_output=True,text=True,check=True)
  return json.loads(p.stdout)
 def test_import_alias_is_recorded_without_claiming_binding(self):
  r=self.extract('package p\nimport proc "os/exec"\nfunc Run(cmd string){proc.Command(cmd)}\n')['calls'][0]
  self.assertEqual(r['import_path_spelling'],'os/exec')
  self.assertEqual(prepare.hints(r),['parameter_command_spelling_hint_not_dataflow'])
  self.assertIn('unresolved',r['semantic_binding'])
 def test_local_import_shadowing_remains_unresolved(self):
  r=self.extract('package p\nimport "os/exec"\nfunc Run(cmd string){exec:=custom;exec.Command(cmd)}\n')['calls'][0]
  self.assertIn('shadowing',r['semantic_binding'])
  self.assertNotIn('positive',r)
 def test_blank_conversion_and_return_is_only_a_spelling_hint(self):
  r=self.extract('package p\nimport "strconv"\nfunc Parse(s string) int {n,_:=strconv.Atoi(s);return n}\n')['calls'][0]
  self.assertEqual(prepare.hints(r),['discarded_error_and_return_spelling_hint_not_dataflow'])
  self.assertNotIn('dataflow_proven',r)
 def test_handled_conversion_and_literal_command_are_not_hints(self):
  rows=self.extract('package p\nimport("strconv";"os/exec")\nfunc Parse(s string)int{n,e:=strconv.Atoi(s);if e!=nil{return 0};exec.Command("fixed");return n}\n')['calls']
  self.assertEqual([prepare.hints(r) for r in rows],[[],[]])
 def test_closure_spellings_do_not_claim_scope_resolution(self):
  r=self.extract('package p\nimport "os/exec"\nfunc Run(cmd string){f:=func(cmd string){exec.Command(cmd)};_=f}\n')['calls'][0]
  self.assertIn('closures',r['semantic_binding'])
 def test_generated_files_are_explicitly_skipped(self):
  r=self.extract('// Code generated by fixture. DO NOT EDIT.\npackage p\nfunc X(){}\n')
  self.assertEqual(r['generated_files_skipped'],['logic.go'])
  self.assertEqual(r['symbols'],[])
 def test_duplicate_names_are_not_arbitrarily_merged(self):
  r=self.extract('package p\nfunc Seed(){}\n','package p\nfunc Seed(){}\n')
  self.assertEqual(len([x for x in r['symbols'] if x['source_name_hint']=='p.Seed']),2)
 def test_git_reader_uses_pinned_commit_not_dirty_checkout(self):
  with tempfile.TemporaryDirectory(prefix='ks-source-git-',dir='/private/tmp') as temp:
   root=Path(temp)
   def git(*args):return subprocess.check_output(['git','-C',str(root),'-c','commit.gpgsign=false',*args],stderr=subprocess.DEVNULL)
   git('init','-q');git('config','user.name','Source fixture');git('config','user.email','fixture@example.invalid')
   (root/'logic.go').write_text('package p\nfunc Old(){}\n');(root/'logic_test.go').write_text('package p\n')
   git('add','.');git('commit','-qm','test: freeze source fixture');commit=git('rev-parse','HEAD').decode().strip()
   (root/'logic.go').write_text('package p\nfunc Dirty(){}\n')
   files=prepare.source_files(root,commit)
   self.assertEqual(len(files),1);self.assertIn('Old',files[0]['Source']);self.assertNotIn('Dirty',files[0]['Source'])
   self.assertIn('Dirty',(root/'logic.go').read_text())

if __name__=='__main__':unittest.main()
