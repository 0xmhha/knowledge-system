type Box struct{ Total int }

func Seed(command string, values []int, strict bool) *exec.Cmd {
	total := 0
	for _, value := range values {
		total += value
	}
	if strict && total < 0 {
		command = "fixed"
	}
	Helper(total)
	return exec.Command(command)
}
