// Package setup turns the knowledge-setup sequence — build the graph index,
// build the vector index aligned to it, verify the two agree — into a typed,
// machine-runnable plan. It replaces the per-project shell scripts that used
// to encode this sequence with hardcoded paths.
//
// The engines are driven through their CLIs as subprocesses (the same
// execution model the fused server's index tool has always used): build
// failures stay isolated from the calling process, and cancellation is a
// process kill. The package deliberately imports no engine internals — the
// CLI flags used here are the compatibility contract, and the boundary check
// enforces the isolation.
package setup

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// Options parameterizes one knowledge-setup plan.
type Options struct {
	// ExternalOrigins are selected local pack roots retained under distinct
	// origin IDs. They never enter the engine's source tree.
	ExternalOrigins []CaptureOrigin
	// RetainedCorporaPrepared prevents regeneration after the snapshot is pinned.
	RetainedCorporaPrepared bool
	// KnowledgeInputs are verified local overlay and selected pack roots.
	// Their bytes contribute to the build recipe and are checked again before
	// promotion. Paths are resolved before this options struct is used.
	KnowledgeInputs []KnowledgeInput
	// ProjectID is assigned once by cks init. Legacy configs may omit it;
	// those builds remain unpinned until explicitly reinitialized.
	ProjectID            string
	SnapshotID           string
	DatasetID            string
	FileManifestDigest   string
	CapturePolicyDigest  string
	SourceMode           string
	MaxGitHistoryBytes   int64
	MaxCaptureFiles      int
	MaxCaptureFileBytes  int64
	MaxCaptureTotalBytes int64
	BuildTimeout         time.Duration
	MinFreeBytes         int64
	LogicalSrcRoot       string
	// Src is the source tree to index. Required.
	Src string
	// Out is the dataset root; the graph index lands in Out/graph and the
	// vector index in Out/vector. Required.
	Out string

	// GraphBin / VectorBin are the engine CLI binaries. Empty values fall
	// back to "ckg" and "ckv" resolved on PATH (the binary names the engine
	// makefiles produce).
	GraphBin  string
	VectorBin string

	// Graph enrichment inputs (optional): governance policy and
	// security-pattern YAML passed through to the graph build.
	PolicyFile          string
	SecurityPatternFile string

	// Vector build knobs (optional). Embedder "" lets the vector CLI pick
	// its default; OllamaURL is exported as CKV_OLLAMA_ENDPOINT.
	Embedder           string
	ModelName          string
	EmbedDim           int
	OllamaURL          string
	QueryPrefixPolicy  string
	VectorBuildSources string // JSON exact Go paths permitted through CKV's build/ default
	// VectorPolicy is the vector chunk-categorization policy YAML.
	VectorPolicy string
	// SemanticCorpus is a separately rendered, reviewed Markdown corpus.
	// Its manifest is checked against the graph build before CKV consumes it.
	SemanticCorpus string
	// DocumentCorpora are explicitly selected ordinary Markdown roots. Unlike
	// SemanticCorpus, they do not claim reviewed semantic projection status.
	DocumentCorpora []string

	// SkipVector builds only the graph index (and skips alignment
	// verification, which needs both).
	SkipVector bool

	// FilelistConfig is an optional build profile (a pack's filelist.yaml).
	// When set, the plan first extracts the build scope into
	// Out/build-scope.json with `ckg scope`, using the profile and
	// BuildOptions, and both engine builds read exactly the files it lists
	// (ckg --scope, ckv --files-from). Unset, both builds read every file.
	FilelistConfig string
	// BuildOptions are the options of the build this dataset follows; set
	// fields override the profile's, so a build with other tags or another
	// target gets the scope of that build.
	BuildOptions BuildOptions

	// DomainKnowledge is a project's domain-knowledge directory (project.yaml,
	// subsystems.yaml, entries/). When set, the plan re-derives the three
	// artifacts that are a pure function of those entries — the embedding
	// corpus, the graph governance policy, and the alias glossary — into
	// DerivedDir before the engine builds consume them.
	//
	// Deriving them per run is the point: these used to be generated by hand
	// and committed, so an entry added months later left the policy and the
	// glossary describing a codebase that no longer existed, with nothing
	// failing to say so.
	DomainKnowledge string
	// DerivedDir is where the domain artifacts land. Empty defaults to
	// "generated" beside the domain-knowledge directory.
	DerivedDir string
	// CodeRoot is the working tree the project's authoritative_docs resolve
	// against. Unset is only viable for a project that declares none — the
	// export step fails rather than shipping a corpus without them.
	CodeRoot string
	// GlossaryFile is the committed alias glossary rendered from the same
	// entries. The fused server reads it at query time to bridge a user's
	// wording to the identifiers in the code, so the build does not consume
	// it — it only checks that it still matches the entries.
	GlossaryFile string
	// FlowCorpus is a curated flow-corpus JSONL embedded alongside the code
	// chunks. Unlike the three derived artifacts this one is hand-authored,
	// so it is consumed straight from the pack.
	FlowCorpus string
	// CksBin is the cks binary hosting the domain toolchain subcommands
	// (`cks domain <tool>`). Empty falls back to "cks" on PATH.
	CksBin string
}

// BuildOptions are per-run build options for the scope extraction.
type BuildOptions struct {
	GOOS, GOARCH string
	CGO          string // "0", "1" or "" (the profile's)
	Tags         []string
	TagsSet      bool // Tags replaces the profile's tags, even when empty
	// Binaries are built binaries the scope is checked against.
	Binaries []string
}

// set reports whether any option changes the extracted scope.
func (b BuildOptions) set() bool {
	return b.GOOS != "" || b.GOARCH != "" || b.CGO != "" || b.TagsSet
}

// scopeArgs are the `ckg scope` flags of the options.
func (b BuildOptions) scopeArgs() []string {
	var a []string
	if b.GOOS != "" {
		a = append(a, "--goos", b.GOOS)
	}
	if b.GOARCH != "" {
		a = append(a, "--goarch", b.GOARCH)
	}
	if b.CGO != "" {
		a = append(a, "--cgo", b.CGO)
	}
	if b.TagsSet {
		a = append(a, "--tags="+strings.Join(b.Tags, ","))
	}
	for _, bin := range b.Binaries {
		a = append(a, "--binary", bin)
	}
	return a
}

type KnowledgeInput struct {
	Role string
	Path string
}

// GraphDir / VectorDir are the per-engine data directories under Out.
func (o Options) GraphDir() string  { return filepath.Join(o.Out, "graph") }
func (o Options) VectorDir() string { return filepath.Join(o.Out, "vector") }

// ScopePath is where the extracted build scope lands (and is read from) when
// FilelistConfig is set — inside the dataset, next to the indexes, so the
// scope and the options it was extracted with travel with the data.
func (o Options) ScopePath() string { return filepath.Join(o.Out, "build-scope.json") }

// derivedRoot is where the domain artifacts land. They are project-level, not
// source-tree-level: the same entries describe every checkout of the project,
// so they sit beside the pack rather than inside one dataset. (The build-scope
// list is the opposite — it comes from one tree's build closure, so it lives
// in the dataset.)
func (o Options) derivedRoot() string {
	if o.DerivedDir != "" {
		return o.DerivedDir
	}
	return filepath.Join(filepath.Dir(o.DomainKnowledge), "generated")
}

// DomainCorpusDir is the rendered embedding corpus. It is the only domain
// artifact written here; the policy and the glossary are committed and merely
// checked against their entries (VerifyDerivedFresh).
func (o Options) DomainCorpusDir() string { return filepath.Join(o.derivedRoot(), "domain-corpus") }

// Step is one unit of the plan: either a subprocess (Cmd non-empty) or an
// internal verification (Verify non-nil).
type Step struct {
	ID    string
	Title string
	Cmd   []string // argv; nil for internal steps
	Env   []string // extra environment (KEY=VALUE), appended to the parent env
	// Verify runs an in-process check for internal steps. It may emit
	// non-fatal findings through the provided callback and returns an error
	// only when the step must fail the plan.
	Verify        func(emit func(Event)) error
	VerifyContext func(context.Context, func(Event)) error
}

// Plan is the ordered step list for one setup run.
type Plan struct {
	Steps []Step
	// Recheck before execution, not just asynchronous planning. A private
	// callback restricts fresh-capture permission to Reindex itself.
	checkTarget func() error
}

// BuildPlan assembles the canonical knowledge-setup sequence:
//
//  1. graph-build   — <graph-bin> build --src SRC --out OUT/graph [enrichment]
//  2. vector-build  — <vector-bin> build --src SRC --out OUT/vector --ckg OUT/graph [...]
//  3. verify-align  — read both manifests, assert same src commit and that
//     the vector index recorded the graph's coordinate pin
//
// The graph build is incremental by definition (the engine reuses its cache
// when OUT/graph already holds a usable manifest), so the same plan serves
// first-time setup and update runs.
func BuildPlan(o Options) (Plan, error) {
	return buildPlan(o, nil)
}

func buildPlan(o Options, captured *CapturedSource) (Plan, error) {
	if o.Src == "" {
		return Plan{}, fmt.Errorf("setup: Src is required")
	}
	if o.Out == "" {
		return Plan{}, fmt.Errorf("setup: Out is required")
	}
	checkTarget := func() error { return CheckMutableTarget(o.Out) }
	if captured != nil {
		checkTarget = func() error { return checkFreshCapturedCandidate(o, *captured) }
	}
	if err := checkTarget(); err != nil {
		return Plan{}, err
	}
	if o.SemanticCorpus != "" && o.SkipVector {
		return Plan{}, fmt.Errorf("setup: semantic corpus requires vector build")
	}
	documentRoots, err := ExtraDocumentRoots(o)
	if err != nil {
		return Plan{}, err
	}
	if len(documentRoots) > 0 && o.SkipVector {
		return Plan{}, fmt.Errorf("setup: document corpora require vector build")
	}
	graphBin := o.GraphBin
	if graphBin == "" {
		graphBin = "ckg"
	}
	vectorBin := o.VectorBin
	if vectorBin == "" {
		vectorBin = "ckv"
	}

	var steps []Step
	if o.DomainKnowledge != "" {
		// The domain toolchain lives in the cks binary (`cks domain <tool>`);
		// one --cks-bin flag replaces the former per-tool binary flags.
		cksBin := o.CksBin
		if cksBin == "" {
			cksBin = "cks"
		}
		exportCmd := []string{cksBin, "domain", "export", "--project", o.DomainKnowledge, "--out", o.DomainCorpusDir()}
		if o.CodeRoot != "" {
			exportCmd = append(exportCmd, "--code-root", o.CodeRoot)
		}
		// The corpus is the one artifact that is genuinely derived here: it
		// is large, nobody reads it by hand, and the vector build consumes it
		// directly. The policy and the glossary stay committed and are only
		// checked — see VerifyDerivedFresh for why.
		if !o.RetainedCorporaPrepared {
			steps = append(steps, Step{
				ID:    "domain-export",
				Title: "Render the domain-knowledge embedding corpus",
				Cmd:   exportCmd,
			})
		}
		if o.PolicyFile != "" {
			argv := []string{cksBin, "domain", "sync", "--project", o.DomainKnowledge, "--ckv-out", os.DevNull, "--ckg-out"}
			steps = append(steps, Step{
				ID:    "policy-fresh",
				Title: "Check the governance policy against the domain entries",
				Verify: func(emit func(Event)) error {
					return VerifyDerivedFresh("policy-fresh", "the governance policy", argv, o.PolicyFile, emit)
				},
				VerifyContext: func(ctx context.Context, emit func(Event)) error {
					return VerifyDerivedFreshContext(ctx, "policy-fresh", "the governance policy", argv, o.PolicyFile, emit)
				},
			})
		}
		if o.GlossaryFile != "" {
			argv := []string{cksBin, "domain", "glossary-gen", "--project", o.DomainKnowledge, "--out"}
			steps = append(steps, Step{
				ID:    "glossary-fresh",
				Title: "Check the alias glossary against the domain entries",
				Verify: func(emit func(Event)) error {
					return VerifyDerivedFresh("glossary-fresh", "the alias glossary", argv, o.GlossaryFile, emit)
				},
				VerifyContext: func(ctx context.Context, emit func(Event)) error {
					return VerifyDerivedFreshContext(ctx, "glossary-fresh", "the alias glossary", argv, o.GlossaryFile, emit)
				},
			})
		}
	}
	if o.FilelistConfig != "" {
		// The scope comes first: the graph and vector builds read only the
		// files it lists. The graph engine extracts it, so the go command
		// it type-checks with is the one that listed the files.
		steps = append(steps, Step{
			ID:    "build-scope",
			Title: "Extract the build scope",
			Cmd: append([]string{graphBin, "scope",
				"--src", o.Src,
				"--profile", o.FilelistConfig,
				"--out", o.ScopePath()}, o.BuildOptions.scopeArgs()...),
		})
	} else if o.BuildOptions.set() || len(o.BuildOptions.Binaries) > 0 {
		return Plan{}, fmt.Errorf("setup: build options need a build profile (filelist)")
	}

	graphCmd := []string{graphBin, "build", "--src", o.Src, "--out", o.GraphDir()}
	if o.LogicalSrcRoot != "" {
		graphCmd = append(graphCmd, "--logical-src-root", o.LogicalSrcRoot)
	}
	if o.DatasetID != "" {
		if o.ProjectID == "" || o.SnapshotID == "" || o.FileManifestDigest == "" || o.CapturePolicyDigest == "" || o.SourceMode == "" {
			return Plan{}, fmt.Errorf("setup: incomplete pinned dataset coordinates")
		}
		graphCmd = append(graphCmd, "--project-id", o.ProjectID, "--snapshot-id", o.SnapshotID,
			"--dataset-id", o.DatasetID, "--file-manifest-digest", o.FileManifestDigest,
			"--capture-policy-digest", o.CapturePolicyDigest,
			"--source-mode", o.SourceMode)
	}
	if o.FilelistConfig != "" {
		graphCmd = append(graphCmd, "--scope", o.ScopePath())
	}
	if o.PolicyFile != "" {
		graphCmd = append(graphCmd, "--policy-file", o.PolicyFile)
	}
	if o.SecurityPatternFile != "" {
		graphCmd = append(graphCmd, "--security-pattern-file", o.SecurityPatternFile)
	}
	steps = append(steps, Step{
		ID:    "graph-build",
		Title: "Build the graph index",
		Cmd:   graphCmd,
	})
	if o.SemanticCorpus != "" {
		steps = append(steps, Step{ID: "semantic-corpus-verify", Title: "Verify reviewed text corpus against the graph snapshot",
			Verify: func(emit func(Event)) error { return VerifyTextCorpus(o.SemanticCorpus, o.GraphDir()) }})
	}

	if !o.SkipVector {
		if len(documentRoots) > 0 {
			steps = append(steps, Step{ID: "document-corpora-verify", Title: "Verify selected document inputs before embedding",
				VerifyContext: func(ctx context.Context, _ func(Event)) error {
					return VerifyDocumentCorpora(ctx, documentRoots, o.CaptureLimits())
				}})
		}
		vectorCmd := []string{vectorBin, "build", "--src", o.Src, "--out", o.VectorDir(), "--ckg", o.GraphDir()}
		if o.LogicalSrcRoot != "" {
			vectorCmd = append(vectorCmd, "--logical-src-root", o.LogicalSrcRoot)
		}
		if o.DatasetID != "" {
			vectorCmd = append(vectorCmd, "--project-id", o.ProjectID, "--snapshot-id", o.SnapshotID,
				"--dataset-id", o.DatasetID, "--file-manifest-digest", o.FileManifestDigest,
				"--capture-policy-digest", o.CapturePolicyDigest,
				"--source-mode", o.SourceMode)
		}
		if o.FilelistConfig != "" {
			vectorCmd = append(vectorCmd, "--files-from", o.ScopePath())
		}
		if o.VectorBuildSources != "" {
			vectorCmd = append(vectorCmd, "--build-sources", o.VectorBuildSources)
		}
		if o.Embedder != "" {
			vectorCmd = append(vectorCmd, "--embedder="+o.Embedder)
		}
		if o.ModelName != "" {
			vectorCmd = append(vectorCmd, "--model-name="+o.ModelName)
		}
		if o.EmbedDim > 0 {
			vectorCmd = append(vectorCmd, fmt.Sprintf("--embed-dim=%d", o.EmbedDim))
		}
		if o.QueryPrefixPolicy != "" {
			vectorCmd = append(vectorCmd, "--query-prefix-policy="+o.QueryPrefixPolicy)
		}
		if o.VectorPolicy != "" {
			vectorCmd = append(vectorCmd, "--policy", o.VectorPolicy)
		}
		if o.DomainKnowledge != "" {
			vectorCmd = append(vectorCmd, "--docs", o.DomainCorpusDir())
		}
		if o.SemanticCorpus != "" {
			vectorCmd = append(vectorCmd, "--docs", o.SemanticCorpus)
		}
		for _, root := range documentRoots {
			vectorCmd = append(vectorCmd, "--docs", root)
		}
		if o.FlowCorpus != "" {
			vectorCmd = append(vectorCmd, "--flow-corpus", o.FlowCorpus)
		}
		var env []string
		if o.OllamaURL != "" {
			env = append(env, "CKV_OLLAMA_ENDPOINT="+o.OllamaURL)
		}
		// Fail fast on an unusable Ollama backend before the long build.
		if o.Embedder == "ollama" {
			url, model := o.OllamaURL, o.ModelName
			steps = append(steps, Step{
				ID:    "vector-preflight",
				Title: "Preflight the Ollama embedder",
				Verify: func(emit func(Event)) error {
					return PreflightOllama(url, model, emit)
				},
			})
		}
		steps = append(steps,
			Step{
				ID:    "vector-build",
				Title: "Build the vector index aligned to the graph",
				Cmd:   vectorCmd,
				Env:   env,
			},
			Step{
				ID:    "verify-align",
				Title: "Verify graph/vector alignment",
				Verify: func(emit func(Event)) error {
					return VerifyAlignment(o.GraphDir(), o.VectorDir(), emit)
				},
			},
		)
		if o.DomainKnowledge != "" || o.FlowCorpus != "" || len(documentRoots) > 0 {
			opts := o
			steps = append(steps, Step{
				ID:    "verify-content",
				Title: "Verify the declared inputs reached the index",
				Verify: func(emit func(Event)) error {
					return VerifyContent(opts, emit)
				},
			})
		}
	}
	return Plan{Steps: steps, checkTarget: checkTarget}, nil
}
